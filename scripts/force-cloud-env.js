/**
 * Script to force the use of cloud Supabase URL
 * 
 * Usage:
 * node scripts/force-cloud-env.js
 */

const fs = require('fs');
const path = require('path');

// Cloud Supabase credentials — sourced from the environment, never hardcoded.
// The URL is public; keep a default for convenience. The anon key must be
// provided (export it or place it in a gitignored .env before running).
const CLOUD_SUPABASE_URL =
  process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://giwurfpxxktfsdyitgvr.supabase.co';
const CLOUD_SUPABASE_ANON_KEY = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!CLOUD_SUPABASE_ANON_KEY) {
  console.error(
    'Set NEXT_PUBLIC_SUPABASE_ANON_KEY in your environment before running this script.'
  );
  process.exit(1);
}

// Create or update .env file
const envPath = path.join(__dirname, '../.env');
const envContent = `# This file is auto-generated by scripts/force-cloud-env.js
# IMPORTANT: Using cloud Supabase instance

# Supabase Cloud Configuration
NEXT_PUBLIC_SUPABASE_URL=${CLOUD_SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${CLOUD_SUPABASE_ANON_KEY}

# Application URL
NEXT_PUBLIC_APP_URL=http://localhost:3000
`;

// Write the .env file
fs.writeFileSync(envPath, envContent);
console.log('.env file updated with cloud Supabase URL');

// Create or update .env.local file
const envLocalPath = path.join(__dirname, '../.env.local');
const envLocalContent = `# This file is auto-generated by scripts/force-cloud-env.js
# IMPORTANT: Using cloud Supabase instance

# Supabase Cloud Configuration
NEXT_PUBLIC_SUPABASE_URL=${CLOUD_SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${CLOUD_SUPABASE_ANON_KEY}

# Application URL
NEXT_PUBLIC_APP_URL=http://localhost:3000
`;

// Write the .env.local file
fs.writeFileSync(envLocalPath, envLocalContent);
console.log('.env.local file updated with cloud Supabase URL');

console.log('Environment files updated successfully. Please restart your application.');
